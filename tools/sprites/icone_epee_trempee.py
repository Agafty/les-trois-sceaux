"""Icône 24x24 de l'Épée trempée (épée de Corvan + minerai d'étoile).
Même dessin que icone_epee_corvan, lame bleu-blanc et éclat étoilé. Python seul."""
import zlib, struct, os
P = {'.': None, 'A': (0x1b,0x14,0x20), 'B': (0xe8,0xf8,0xff), 'C': (0x8a,0xea,0xf8),
     'D': (0x2a,0x88,0xc8), 'E': (0xc8,0xa0,0x50), 'F': (0x24,0x1a,0x22),
     'G': (0x8a,0x5a,0x34), 'H': (0x5e,0x3a,0x22), 'W': (0xff,0xff,0xff), 'S': (0x4a,0xc8,0xe8)}
G = """
........................
........................
....................AA..
...................ABBA.
..................ABBBA.
.................ABBCDA.
................ABBCDA..
...............ABBCDA...
..............ABBCDA....
......A......ABBCDA.....
.....AEA....ABBCDA......
.....AEEA..ABBCDA.......
....AEAFFAABBCDA........
.....AGEFFBBCDA.........
......AGFFECDA..........
.......AGFFEAA..........
......AHHGAEEGA.........
.....AHHGAGAEEA.........
....AHHGA.AGAA..........
..AAHHGA...A............
.AEEEAA.................
..AEEA..................
...AA...................
........................""".strip('\n').split('\n')
g = [list(r) for r in G]
# éclat étoilé (croix de 5 px) au centre de la lame, plus un scintillement
for (x, y, c) in [(14,8,'W'),(14,7,'S'),(14,9,'S'),(13,8,'S'),(15,8,'S'),
                  (20,3,'W'),(10,5,'S'),(9,5,'W'),(10,4,'S'),(10,6,'S'),(11,5,'S')]:
    g[y][x] = c
# le scintillement hors lame (10,5) reste sans contour : voulu (éclat flottant)
w = h = 24
raw = b''
for r in g:
    raw += b'\0' + b''.join(bytes(P[c]) + b'\xff' if P[c] else b'\0\0\0\0' for c in r)
def ch(t, d):
    c = struct.pack('>I', len(d)) + t + d
    return c + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
png = b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) + ch(b'IDAT', zlib.compress(raw, 9)) + ch(b'IEND', b'')
out = os.path.join(os.path.dirname(__file__), '..', '..', 'art', 'ui', 'icone_epee_trempee.png')
open(out, 'wb').write(png)
